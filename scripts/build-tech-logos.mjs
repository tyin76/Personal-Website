// Generates src/data/techLogos.js from the simple-icons package (CC0 brand marks).
// Run with: npm run build-logos
import * as icons from 'simple-icons';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// skill label as used in src/data/skills.js -> simple-icons export name
const map = {
  React: 'siReact', TypeScript: 'siTypescript', JavaScript: 'siJavascript', Python: 'siPython', Java: 'siOpenjdk',
  C: 'siC', 'C++': 'siCplusplus', HTML: 'siHtml5', CSS: 'siCss', Redux: 'siRedux', Django: 'siDjango', Node: 'siNodedotjs',
  Express: 'siExpress', Tailwind: 'siTailwindcss', 'Material UI': 'siMui', Jest: 'siJest', Mocha: 'siMocha', Chai: 'siChai',
  JUnit: 'siJunit5', PostgreSQL: 'siPostgresql', MongoDB: 'siMongodb', Firebase: 'siFirebase', 'Google Cloud': 'siGooglecloud',
  Docker: 'siDocker', Git: 'siGit', GitHub: 'siGithub', Oracle: 'siOracle', Postman: 'siPostman', Railway: 'siRailway',
  Figma: 'siFigma', JupyterLab: 'siJupyter',
};
// near-black brand colours are invisible on a dark theme; render these in the text colour instead
const darkBrands = new Set(['siGithub', 'siExpress', 'siOpenjdk', 'siRailway', 'siMocha']);

const lines = ['// Generated by scripts/build-tech-logos.mjs from simple-icons. Do not edit by hand.', 'const techLogos = {'];
const missing = [];
for (const [label, name] of Object.entries(map)) {
  const icon = icons[name];
  if (!icon) { missing.push(name); continue; }
  const color = darkBrands.has(name) ? '#e8ecf3' : `#${icon.hex}`;
  lines.push(`  ${JSON.stringify(label)}: { color: '${color}', path: '${icon.path}' },`);
}
lines.push('};', '', 'export default techLogos;', '');
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
await writeFile(path.join(root, 'src/data/techLogos.js'), lines.join('\n'));
console.log(`wrote ${Object.keys(map).length - missing.length} logos${missing.length ? `, missing: ${missing.join(', ')}` : ''}`);
